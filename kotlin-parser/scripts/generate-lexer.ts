// Translate the pinned upstream DFA tables and action bodies; fail on unknown syntax.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { basename } from 'node:path';
const source = await readFile(new URL('../upstream/_JetLexer.java', import.meta.url), 'utf8');
const metadata = JSON.parse(await readFile(new URL('../upstream/metadata.json', import.meta.url), 'utf8'));
if (createHash('sha256').update(source).digest('hex') !== metadata.lexerSha256) throw new Error('Upstream source checksum mismatch');
for (const entry of metadata.parserSources) {
  const file = new URL(`../upstream/parsing/${basename(entry.path)}`, import.meta.url);
  const contents = await readFile(file);
  if (createHash('sha256').update(contents).digest('hex') !== entry.sha256) {
    throw new Error(`Upstream source checksum mismatch: ${entry.path}`);
  }
}
const target = new URL('../src/commonMain/kotlin/li/songe/kotlin/lexer/', import.meta.url);
await mkdir(target, { recursive: true });
const header = `// Derived from JetBrains Kotlin ${metadata.version}, Apache-2.0. Generated by scripts/generate-lexer.ts.\npackage li.songe.kotlin.lexer\n\n`;
function decode(literal: string): number[] {
  const result: number[] = [];
  for (let i = 0; i < literal.length; i++) {
    if (literal[i] !== '\\') { result.push(literal.charCodeAt(i)); continue; }
    const tail = literal.slice(++i);
    const unicode = /^u([0-9a-fA-F]{4})/.exec(tail);
    const octal = /^[0-7]{1,3}/.exec(tail);
    if (unicode) { result.push(parseInt(unicode[1], 16)); i += 4; }
    else if (octal) { result.push(parseInt(octal[0], 8)); i += octal[0].length - 1; }
    else { const escapes: Record<string, number> = { n: 10, r: 13, t: 9, b: 8, f: 12, '"': 34, '\\': 92 }; if (!(tail[0] in escapes)) throw new Error('Unknown Java escape'); result.push(escapes[tail[0]]); }
  }
  return result;
}
const tableNames = ['CMAP_TOP', 'CMAP_BLOCKS', 'ACTION', 'ROWMAP', 'TRANS', 'ATTRIBUTE'];
let tables = header + 'internal object LexerTables {\n';
for (const name of tableNames) {
  const match = new RegExp(`ZZ_${name}_PACKED_0\\s*=([\\s\\S]*?);`).exec(source);
  if (!match) throw new Error(`Missing table ${name}`);
  const packed = [...match[1].matchAll(/"((?:\\.|[^"\\])*)"/g)].flatMap(m => decode(m[1]));
  // Keep packed tables compact; unpack once in common Kotlin on either target.
  tables += `    val ${name} = unpack("${packed.join(',')}", ${name === 'ROWMAP'}, ${name === 'TRANS'})\n`;
}
tables += String.raw`
    private fun unpack(data: String, rowMap: Boolean, subtract: Boolean): IntArray {
        val packed = data.split(',').map { it.toInt() }
        if (rowMap) return IntArray(packed.size / 2) { (packed[it * 2] shl 16) or packed[it * 2 + 1] }
        val out = IntArray(packed.indices.step(2).sumOf { packed[it] })
        var j = 0
        for (i in packed.indices step 2) repeat(packed[i]) { out[j++] = packed[i + 1] - if (subtract) 1 else 0 }
        return out
    }
}
`;
await writeFile(new URL('LexerTables.kt', target), tables);
const states = [...source.matchAll(/public static final int (\w+) = (-?\d+);/g)];
const lexStates = /ZZ_LEXSTATE\[\]\s*=\s*\{([^}]+)\}/.exec(source)![1];
let actions = header + 'internal fun PortableLexer.runAction(action: Int): String? {\n    when (action) {\n';
const actionSource = source.slice(source.indexOf('switch (zzAction < 0'));
let count = 0;
for (const match of actionSource.matchAll(/case (\d+):\s*\{([\s\S]*?)\}\s*\/\/ fall through/g)) {
  let body = match[2].replace(/\/\/[^\n]*/g, '')
    .replace(/\b(?:KtTokens|TokenType)\.(\w+)/g, '"$1"')
    .replace(/\bint (\w+) =/g, 'var $1 =')
    .replace(/for \(var i = 0; i < yylength\(\); i\+\+\)/g, 'for (i in 0 until yylength())')
    .replace(/Math.max/g, 'maxOf').replace(/yytext\(\)\.length\(\)/g, 'yylength()');
  if (/\b(?:int|new|switch|KtTokens|TokenType)\b/.test(body)) throw new Error(`Untranslated action ${match[1]}`);
  actions += `        ${match[1]} -> { ${body.trim()} }\n`;
  count++;
}
if (count !== 108) throw new Error(`Expected 108 actions, found ${count}`);
actions += '        else -> error("No lexer match: " + action)\n    }\n    return null\n}\n\n';
actions += states.map(m => `internal const val ${m[1]} = ${m[2]}`).join('\n') + '\n';
actions += `internal val LEX_STATES = intArrayOf(${lexStates.trim().replace(/,\s*$/, '')})\n`;
await writeFile(new URL('LexerActions.kt', target), actions);
console.log(`Generated ${tableNames.length} DFA tables and ${count} actions from verified Kotlin ${metadata.version}`);
